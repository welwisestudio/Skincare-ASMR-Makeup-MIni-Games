import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[],external=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('response',r=>{if(r.status()>=400)errors.push(`${r.status()} ${r.url()}`);});
page.on('request',r=>{const url=new URL(r.url());if(['http:','https:','ws:','wss:'].includes(url.protocol)&&url.host!=='localhost:4173')external.push(r.url());});
await page.goto('http://localhost:4173');await page.waitForSelector('#start-button');
assert.equal(await page.evaluate(()=>typeof window.__spa),'undefined','Production must not expose debug state');
await page.screenshot({path:'test-results/production-desktop.png'});
await page.setViewportSize({width:390,height:844});await page.waitForTimeout(200);
await page.click('#start-button');await page.waitForTimeout(300);
const x=195,y=365;
await page.mouse.move(x,y);await page.mouse.down();await page.waitForTimeout(1100);await page.mouse.up();
assert.notEqual(await page.locator('#progress-label').textContent(),'0%','Production treatment accepts pointer input');
await page.click('#pause-button');await page.click('#resume-button');
await page.setViewportSize({width:390,height:844});await page.waitForTimeout(350);await page.screenshot({path:'test-results/production-mobile.png'});
await page.setViewportSize({width:844,height:390});await page.waitForTimeout(350);await page.screenshot({path:'test-results/production-landscape.png'});
await page.click('#home-button');await page.waitForSelector('.level-card');await page.waitForTimeout(1000);await page.screenshot({path:'test-results/production-menu.png'});
await page.click('#menu-daily');await page.click('#daily-claim');await page.click('#reward-continue');
assert.equal(await page.isDisabled('#daily-claim'),true);await page.click('#meta-close');
await page.click('#nav-pass');await page.click('#pass-watch');await page.waitForFunction(()=>!document.getElementById('ad-complete')?.disabled);await page.click('#ad-complete');await page.click('#reward-continue');await page.click('#meta-close');
const save=await page.evaluate(()=>JSON.parse(localStorage.getItem('skincare-asmr-v1')));assert.equal(save.passAds,1);assert.equal(save.coins,150);
assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
await writeFile('test-results/production-report.json',JSON.stringify({builtBundle:true,debugAbsent:true,pointerInput:true,pause:true,menu:true,dailyClaim:true,rewardedPreview:true,externalRequests:external,errors},null,2));console.log('Production bundle, input, daily reward and preview ad: PASS. No external requests.');
await browser.close();
