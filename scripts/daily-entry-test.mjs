import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {freshSave} from '../src/save.js';
import {dayKey} from '../src/meta-content.js';
import {bridgeDouble} from './bridge-double.mjs';
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const page=await browser.newPage({viewport:{width:390,height:844}}),errors=[];
let cloud='';
page.on('pageerror',e=>errors.push(e.message));
await page.exposeFunction('__cloudRead',()=>cloud);
await page.exposeFunction('__cloudWrite',data=>{cloud=data;});
await page.route('**/playgama-bridge.js',route=>route.fulfill({contentType:'application/javascript',body:bridgeDouble({audio:false})}));
const mode=()=>page.evaluate(()=>window.__spa.app.ui.mode);
const reload=async()=>{await page.goto(process.env.GAME_URL||'http://localhost:5173');await page.waitForFunction(()=>window.__spa?.app.ui&&window.__spa.app.state!=='loading');};
try{
 await reload();assert.equal(await mode(),'levels');
 assert.equal(await page.locator('#nav-rewards').textContent(),'MY GIFTS');
 await page.setViewportSize({width:400,height:850});
 await page.evaluate(()=>window.__spa.app.ui.render(false));assert.equal(await mode(),'levels');
 await page.click('#nav-rewards');await page.evaluate(()=>window.__spa.app.backMeta());assert.equal(await mode(),'daily');
 await page.evaluate(()=>window.__spa.app.backMeta());assert.equal(await mode(),'levels');
 await page.click('#nav-rewards');await page.evaluate(()=>window.__spa.app.backMeta());assert.equal(await mode(),'levels');
 await page.evaluate(()=>window.__spa.app.platform.flush());assert.equal(JSON.parse(cloud).hasLaunched,true);
 await reload();assert.equal(await mode(),'daily');
 await page.evaluate(()=>window.__spa.app.claimDaily());
 await page.evaluate(()=>window.__spa.app.backMeta());assert.equal(await mode(),'levels');
 await page.click('#menu-daily');assert.equal(await mode(),'daily');
 assert.equal(await page.locator('#daily-claim').isDisabled(),true);
 const dailyBefore=await page.evaluate(()=>JSON.stringify(window.__spa.app.save));
 await page.evaluate(()=>window.__spa.app.claimDaily());
 assert.equal(await page.evaluate(()=>JSON.stringify(window.__spa.app.save)),dailyBefore);
 await page.evaluate(()=>window.__spa.app.backMeta());assert.equal(await mode(),'levels');
 await page.evaluate(()=>window.__spa.app.platform.flush());
 await reload();assert.equal(await mode(),'levels');
 await page.click('#menu-daily');assert.equal(await mode(),'daily');
 assert.equal(await page.locator('#daily-claim').isDisabled(),true);
 await page.evaluate(()=>window.__spa.app.backMeta());assert.equal(await mode(),'levels');
 const legacy=freshSave();delete legacy.hasLaunched;cloud=JSON.stringify(legacy);
 await reload();assert.equal(await mode(),'daily');
 const claimed=freshSave();claimed.hasLaunched=true;claimed.daily={claims:1,lastDay:dayKey(Date.now()-86400000)};cloud=JSON.stringify(claimed);
 await reload();assert.equal(await mode(),'daily');
 await page.evaluate(()=>window.__spa.app.backMeta());
 const icons=await page.evaluate(()=>window.__spa.app.ui.root.list.flatMap(x=>x.list||[]).filter(x=>x.texture).map(x=>x.texture.key));
 assert.ok(icons.includes('ui-rose-bow'));
 assert.deepEqual(errors,[]);
 console.log('PASS: first session second menu entry; redraw ignored; once per session; returning/legacy players; claimed and next-day rewards; MY GIFTS bow');
}finally{await browser.close();}
